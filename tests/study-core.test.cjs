const assert = require('node:assert/strict');
const S = require('../assets/study-core.js');
const fs = require('node:fs');
const data = JSON.parse(fs.readFileSync(__dirname+'/../tutorial/study/plan.json','utf8'));
assert.equal(data.days.length,77);
assert.equal(S.dateAt('2026-10-26',76),'2027-01-10');
assert.equal(S.indexAt('2026-10-26','2026-11-01'),6);
assert.equal(S.indexAt('2026-10-26','2026-10-25'),-1);
assert.equal(S.validDate('2026-02-30'),false);
assert.equal(S.validDate('2028-02-29'),true);
for(const d of data.days) assert.equal(d.minutes.reduce((a,b)=>a+b,0),90);
assert.equal(S.nextPending({done:{}},data),0);
assert.equal(S.nextPending({done:{d01:[true,true,true,true,true]}},data),1);
assert.equal(S.normalize({start:'bad',minutes:999,done:{oops:[true]}},data).start,data.start);
assert.equal(S.normalize({done:{d01:[true,'true',1,true,false]}},data).done.d01.filter(Boolean).length,2);
assert.equal(S.normalize({notes:{d01:'x'.repeat(20000)}},data).notes.d01.length,10000);
assert.equal(S.totalMinutes(data.days[0],120),120);
assert.equal(S.totalMinutes(data.days[0],150),150);
assert.equal(S.isComplete([true,true,true,true,false]),false);
console.log('study-core: 77 days, date boundaries, time budgets, progress validation PASS');
